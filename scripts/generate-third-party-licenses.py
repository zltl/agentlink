#!/usr/bin/env python3
"""Write THIRD_PARTY.md from `cargo metadata` and in-tree license files.

Does not invent licenses. A crate with no `license` or `license-file` in
its cargo metadata is recorded as undeclared. Re-run from the repository
root after a lockfile change:

    python3 scripts/generate-third-party-licenses.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY.md"


def cargo_metadata() -> dict:
    cmd = [
        "cargo",
        "metadata",
        "--format-version",
        "1",
        "--offline",
        "--locked",
        "--manifest-path",
        str(ROOT / "Cargo.toml"),
    ]
    raw = subprocess.check_output(cmd, cwd=ROOT)
    return json.loads(raw)


def main() -> int:
    meta = cargo_metadata()
    workspace = set(meta.get("workspace_members") or [])
    first_party = []
    third_party = []
    undeclared = []
    for pkg in meta["packages"]:
        name = pkg["name"]
        version = pkg["version"]
        ident = f"{name} {version}"
        license_id = (pkg.get("license") or "").strip()
        license_file = (pkg.get("license_file") or "").strip()
        repository = (pkg.get("repository") or "").strip()
        row = {
            "name": name,
            "version": version,
            "license": license_id,
            "license_file": license_file,
            "repository": repository,
            "id": pkg.get("id") or ident,
        }
        if pkg.get("id") in workspace:
            first_party.append(row)
            continue
        if license_id or license_file:
            third_party.append(row)
        else:
            undeclared.append(row)

    def key(row: dict) -> tuple[str, str]:
        return (row["name"].lower(), row["version"])

    first_party.sort(key=key)
    third_party.sort(key=key)
    undeclared.sort(key=key)

    lines = []
    lines.append("# Third-party licenses")
    lines.append("")
    lines.append("Generated by `scripts/generate-third-party-licenses.py` from")
    lines.append("`cargo metadata --format-version 1 --offline --locked`.")
    lines.append("Do not edit this file by hand; re-run the script after a")
    lines.append("lockfile or asset change. License identifiers are copied from")
    lines.append("each crate's cargo metadata `license` / `license-file` fields.")
    lines.append("Nothing here is inferred from a crate name or guessed.")
    lines.append("")
    lines.append(f"Workspace members: {len(first_party)}.")
    lines.append(
        f"Third-party crates with a declared license or license-file: {len(third_party)}."
    )
    lines.append(
        f"Third-party crates with no license field in cargo metadata: {len(undeclared)}."
    )
    lines.append("")
    lines.append("## First-party workspace crates")
    lines.append("")
    lines.append("Licensed as declared in the workspace (`MIT OR Apache-2.0`).")
    lines.append("See `LICENSE-MIT`, `LICENSE-APACHE`, and `NOTICE`.")
    lines.append("")
    for row in first_party:
        declared = row["license"] or "(workspace license; crate metadata license field empty)"
        lines.append(f"- `{row['name']} {row['version']}` — {declared}")
    lines.append("")
    lines.append("## Third-party Rust crates (from Cargo.lock / cargo metadata)")
    lines.append("")
    lines.append("| Crate | Version | License (cargo metadata) | Repository |")
    lines.append("| --- | --- | --- | --- |")
    for row in third_party:
        license = row["license"] or f"license-file: {row['license_file']}"
        repo = row["repository"] or ""
        lines.append(
            f"| `{row['name']}` | {row['version']} | {license} | {repo} |"
        )
    lines.append("")
    lines.append("## Third-party crates with no license in cargo metadata")
    lines.append("")
    if undeclared:
        lines.append("The generator did not invent a license for these crates.")
        lines.append("")
        for row in undeclared:
            extra = []
            if row["repository"]:
                extra.append(row["repository"])
            if row["license_file"]:
                extra.append("license-file=" + row["license_file"])
            suffix = f" ({'; '.join(extra)})" if extra else ""
            lines.append(f"- `{row['name']} {row['version']}`{suffix}")
    else:
        lines.append("None. Every third-party crate in this lockfile declared a")
        lines.append("`license` or `license-file` field in cargo metadata.")
    lines.append("")
    lines.append("## Embedded assets in this repository")
    lines.append("")
    lines.append("Only licenses found next to the files, or clearly documented")
    lines.append("in-tree, are listed. First-party artwork is covered by the")
    lines.append("workspace license.")
    lines.append("")
    lines.append("- `crates/agentlink-cli/assets/Inter-Regular.ttf`,")
    lines.append("  `Inter-Medium.ttf`, `Inter-SemiBold.ttf` — SIL Open Font")
    lines.append("  License 1.1, as included in")
    lines.append("  `crates/agentlink-cli/assets/Inter-LICENSE.txt`.")
    lines.append("- `crates/agentlink-cli/assets/JetBrainsMono-Regular.ttf` —")
    lines.append("  SIL Open Font License 1.1, as included in")
    lines.append("  `crates/agentlink-cli/assets/JetBrainsMono-OFL.txt`.")
    lines.append("- `crates/agentlink-cli/assets/agentlink-octopus.svg`,")
    lines.append("  `agentlink.ico`, and `docs/*.svg` — first-party workspace")
    lines.append("  files; no separate third-party license file is present.")
    lines.append("- Noto Sans CJK is not bundled. The Controller may load a")
    lines.append("  system or drop-in copy; see `crates/agentlink-cli/src/controller/fonts.rs`.")
    lines.append("")
    lines.append("Android/Gradle library licenses are not in this inventory.")
    lines.append("Those artifacts are declared in `android/app/build.gradle.kts`;")
    lines.append("this generator only reads cargo metadata and the in-tree")
    lines.append("asset license files above.")
    lines.append("")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(third_party)} third-party crates, {len(undeclared)} undeclared)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
